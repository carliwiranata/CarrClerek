-- Audit log and server-side attempt limiting for CarrClerek Stock Opname access.
create table if not exists public.stock_opname_access_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  store_id text,
  success boolean not null default false,
  created_at timestamptz not null default now()
);

create index if not exists stock_opname_access_attempts_user_created_idx
  on public.stock_opname_access_attempts (user_id, created_at desc);

alter table public.stock_opname_access_attempts enable row level security;

-- No client policies are created. Only the Edge Function service role can read/write this table.
